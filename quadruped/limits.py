"""动作参数的上下限：一处定义，通讯层与 A 模型共用。

这些数字不是「礼貌值」，是边界。越过去之后的失效方式写在各自注释里，改之前先读。

通讯层（`comm/protocol.py`）用它校验外部请求，A 模型（`quadruped/action.py`）用它
裁剪模型输出。两边共用同一份，是因为上下限一旦漂移，表现是「从命令行发 0.4 能走，
从模型发 0.4 被拒」—— 这种不一致不会报错，只会让人怀疑模型。
"""

# -- 持续速度指令 ------------------------------------------------------------
# 上限直接取策略的训练范围，不在这里再写一个数。
#
# 原来写 0.40，理由是「search 档声明的 speed_range 上界，再高 stride_max 削顶，
# 落地速度对不上，脚在原地打滑」—— 那条只对**自研控制器**成立：它的步幅由
# `Go2Robot` 的 stride_max 直接决定，超了就削。策略网络没有 stride 这个量，步幅
# 是它从 vx / freq / footswing 自己推出来的，用 0.40 管它等于凭空夹住一半行程。
#
# 实测（`test/policy_sim.py`，8 s）：vx 0.4 走 1.217 m，1.0 走 1.894 m
# （配 freq 2.0 是 2.048 m），倾角 12.9° → 17.6°。真机没量过。
#
# 这个模块不许 import 项目里的任何模块（`test/arch_check.py` 规则 3），所以两个上限
# 在这里写成字面量，与 `walker.COMMAND_RANGE` 的一致性由 `test/policy_audit.py` 管。
VX_MAX = 1.0

# 横移是**有意比训练范围更严**的：训练范围 ±0.6，这里 0.3。超过 0.3 四条腿的
# 侧向行程不够，摆动腿会蹭地。所以这一项不从 `COMMAND_RANGE` 取，是真正的额外限制。
VY_MAX = 0.30

# 角速度上限同样取策略的训练范围（±4.0）。原值 0.80，注释写着「和键盘遥控的
# 上限一致」—— 键盘早已改成 4.0/2.0/1.0，这句话先失效；更要紧的是策略在 0.8 下
# 原地只出约 0.1 rad/s，等于「远程控制转不动」。
#
# 自研运控吃的是真实 rad/s，4.0 会把它甩出去 —— 那个边界由它自己守，见
# `Go2Controller.set_velocity` 里的夹取。两边各管各的范围，不再共用一个数。
VYAW_MAX = 4.0

# -- 决策提前量 --------------------------------------------------------------
# 前方这么近就当作「要撞了」：L 层立刻重想、G 层立刻换向、提示词里也写这个数。
#
# 一开始三处各写一个（think 0.6 / drive 0.8 / 提示词 1.2），现在只有这里一处。
#
# 为什么是 1.8 而不是 1.2 —— 算物理账（2026-11-15 实测口径）：
#
#     一次决策   1.0 s 生成 + 下发        → 走 0.5 m（vx 0.9 实测 0.5 m/s）
#     转 90°     2.8 s，带 0.15 前进      → 再走 0.5 m
#     合计                                → 1.0 m，还没算打滑和响应延迟
#
# 1.2 m 只剩 0.2 m 余量，所以还是「贴到墙角才开始转」（用户截图：狗站在东北角
# 才转）。取 1.8 留一半余量。再大就会在走廊中间因为正前方的端墙频繁触发。
GAP_TRIGGER = 1.8

# 「该开始转向」的距离。**和上面那个不是一回事。**
#
# `GAP_TRIGGER` 管的是「什么时候重想一次」（提前知道前面有墙，好早点打算）。
# 这个管的是「离墙多近才真的转」。两件事混在一个数上，后果很具体：
#
# 2026-11-17 迷宫 VLA，提示词里写着「前方不到 1.8 米就开始转」，于是狗在
# **1.49 米**就拐了 —— 0.7 米长的机身，1.49 米够走两步。转过去前方还是 1.4 米，
# 又是「不到 1.8，该转」，再转。22 次转向、累计 1692°、走 30.9 米只挪出 3.9 米，
# 轨迹在东端 x=2.7 处就掉头（东墙在 4.5）。
#
# 1.2 的依据是真实的制动距离：一次决策 1.0 s 走 0.5 m，转 90° 带 0.15 前进再走
# 0.5 m，合计 1.0 m。1.2 留 0.2 m 余量，是「还来得及」的最小值 —— 再小就真贴上了。
#
# `think.TURN_FREE_GAP` 和提示词里的那句话都取这个数，三处一个值。
TURN_START_GAP = 1.2

# -- 闭环位移 ----------------------------------------------------------------
# 单次最多 3 m。再长就分两次：里程计积分漂移会累积，走完 3 m 之后进度条的
# 绝对值已经不是米了。
FORWARD_MAX = 3.0
FORWARD_VX = 0.30
# 下限 0.05 m/s：timeout 按 |distance|/vx 算，vx 趋零时这个除法会炸。
FORWARD_VX_MIN = 0.05

# -- 闭环转向 ----------------------------------------------------------------
# 超过 180° 分两次转。IMU 的 yaw 积分单次转得越多误差越大，且中间没有视觉校准点。
TURN_MAX = 180.0
TURN_RATE = 0.50
TURN_RATE_MIN = 0.05

# -- 蹲下 --------------------------------------------------------------------
CROUCH = 0.08
CROUCH_MIN = 0.02
# 上限 0.18 m 是腿折到极限之前留的余量，再深膝盖会顶到机械限位。
CROUCH_MAX = 0.18
