"""各层的频率，只在这一个文件里定义。

分散在 `camera.py` / `think.py` / `drive.py` / `simulate_python/percept_pub.py`
的默认参数里也能跑，但「视觉是多少赫兹」这种问题要翻四个文件才能回答，而且改了一处
忘记另一处时不会有任何报错 —— 只会在实测时表现为「怎么比说好的慢」。

    G 目标    0.10 Hz   10 秒复查一次；受阻立刻改
    L 决策    2 Hz 节拍，推理上限 1 Hz；自驱时想完接着想，空闲 1/6 Hz
    R 反射    20 Hz     取感知 + 查安全闸，不经过模型
    V 语义    0.33 Hz   画面变了才问视觉模型
    V 几何    10 Hz     仿真侧发布射线
    C 策略    50 Hz     力矩回路

这些数不是「越多越好」调出来的上界，每一个都是等出来的：

    策略 50 Hz    训练时就是 20 ms 一帧，改这个数等于换一个策略
    射线 10 Hz    0.3 m/s 走 0.1 m；再低，台阶会在两帧之间滑过去
    反射 20 Hz    0.3 m/s 走 0.015 m，比一个摆动相（0.2 m）短一个数量级
    L 推理 1 Hz   一次 DeepSeek 往返 0.7~1.3 s，间隔低于 1 s 时上一句还没执行完
                  就被覆盖（本地 1.5B 是 2 s，和视觉并发时 4 s）
    V 语义 0.33 Hz 一次往返 0.9~1.2 s。本地两个模型会抢同一块 GPU，换远程后
                  不再互拖；限制它的只剩「画面多久变一次」
    目标 0.1 Hz   10 s 内走 3 m，比一次 L 层决策粗一个数量级，再高没有新信息

## 为什么 L 层是「节拍」和「上限」两个数

节拍管的是续期命令、读感知、查闸，这些都很便宜（微秒级），2 Hz 足够；
推理管的是调模型，很贵。合成一个数的话，要么续期太慢（3 秒超时会让狗走两步停下），
要么一直在调模型。两个数分开，静止时占空比接近 0。
"""

from __future__ import annotations

# ---- 感知 ----------------------------------------------------------------

PERCEPT_HZ = 10.0           # 仿真发布射线（`percept_pub.py` 的 hz 默认值）
CAMERA_HZ = 30.0            # 仿真发布相机画面（同上，video_hz）
                            # 5 Hz 那一版遥操作没法用：一帧之间狗已经挪了 16 cm。
                            # 这只是「标称」，实际还受网关 --cam-hz 与
                            # percept.feed --hz 限制（两者默认也是 30）。

# ---- V 层语义 ------------------------------------------------------------

# 1 Hz。原来是 1/3：一次问模型 ~1.0 s，加上 3 s 的最小间隔，实际 2~3 s 一跳。
# 狗 0.8 m/s 走 2.4 m 才看一眼，而 1.8 m 的走廊里 2.4 m 已经撞上了 —— 视觉再准，
# 采样跟不上也是摆设。1 Hz 下每 0.8 m 看一眼，代价是每秒一次图片请求。
VLM_HZ = 1.0                # 视觉模型最多 1 秒问一次（`camera.VisionPercept`）
VLM_MIN_CHANGE = 0.03       # 缩略图平均绝对差超过这个值才问

# ---- R 层反射 ------------------------------------------------------------

REFLEX_HZ = 20.0            # 取感知 + 查安全闸（`percept/reflex.py`）

# ---- L 层决策 ------------------------------------------------------------

THINK_TICK_HZ = 2.0         # 节拍：读感知、续期命令、判要不要推理
THINK_MAX_HZ = 1.0          # 推理上限
THINK_IDLE_HZ = 1.0 / 6.0   # 没人管、也没有事件时的复查频率

# ---- G 层目标 ------------------------------------------------------------

GOAL_HZ = 1.0 / 10.0        # 自驱时复查目标的频率

# ---- C 层执行 ------------------------------------------------------------

POLICY_HZ = 50.0            # 推理策略 / 训练时的控制频率
MOTION_HZ = 500.0           # `MotionService` 下发 LowCmd 的频率


# 给人看的一张表。启动时打一遍，读日志时不用回头翻代码。
def table() -> list[tuple[str, str, str]]:
    return [
        ("G 目标", f"{GOAL_HZ:.2f} Hz", "10 s 复查；受阻立刻改"),
        ("L 决策", f"{THINK_TICK_HZ:g} Hz",
         f"节拍；推理 <= {THINK_MAX_HZ:g} Hz，自驱按间隔接着想"),
        ("R 反射", f"{REFLEX_HZ:g} Hz", "取感知 + 安全闸，不调模型"),
        ("V 语义", f"{VLM_HZ:.2f} Hz", "问视觉模型：画面三块能不能过"),
        ("V 几何", f"{PERCEPT_HZ:g} Hz", "测距：仿真射线 / 真机雷达（--geom）"),
        ("V 画面", f"{CAMERA_HZ:g} Hz", "仿真侧发布相机图"),
        ("C 策略", f"{POLICY_HZ:g} Hz", "力矩回路"),
    ]


def describe() -> str:
    return "\n".join(f"  {name:8s} {hz:>9s}  {note}" for name, hz, note in table())


# 窗口标题行用的一行缩写。
def headline() -> str:
    return (f"G {GOAL_HZ:.2f}  L {THINK_MAX_HZ:g}  R {REFLEX_HZ:g}  "
            f"V {VLM_HZ:.2f}  C {POLICY_HZ:g} Hz")
