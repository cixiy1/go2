# 走 —— 关掉 thought 时示例里还带 thought，它会把形状抄回来。
def _example(has_rays: bool) -> str:
    if has_rays:
        seen = "视野：正前 0.52 m 墙，左侧 3.00 m 空"
        why, turn = "正前贴墙、左侧是空的，左转找没走过的方向", 80
    else:
        seen = ("画面：左：墙壁，不能，很近(1米内)\n"
                "       中：墙壁，不能，很近(1米内)\n"
                "       右：空地，能，远(3米外)")
        why, turn = "正中贴墙、右侧那块写着能过，右转", -70
    cmd = (f'{{"thought": "{why}", "command": {{"vyaw": {turn}}}}}' if EMIT_THOUGHT
           else f'{{"command": {{"vyaw": {turn}}}}}')
    # 回话的示例。`command` 是空的 —— 用户在问话时，正确做法就是只答不加动作。
    # 这条不随 `EMIT_THOUGHT` 分叉：`reply` 与 thought 是两个独立字段。
    talk = (f'{{"thought": "正前 2 米空、左侧贴墙", "reply": "正前两米是空地，'
            f'左边一堵墙", "command": {{}}}}' if EMIT_THOUGHT
            else '{"reply": "正前两米是空地，左边一堵墙", "command": {}}')
    return (f"例：\n{seen}\n输出：{cmd}\n\n"
            f"例（用户在说话，只答不动）：\n用户：你看到什么\n输出：{talk}\n")


# 系统提示词。`has_rays` 决定输入说明和示例用哪一版，见 `_think_body`。
def think_system(has_rays: bool = True) -> str:
    out = _OUT_WITH_THOUGHT if EMIT_THOUGHT else _OUT_PLAIN
    return _think_body(has_rays) + out + _example(has_rays)


THINK_SYSTEM = think_system(True)


# 拼 L 层的一次对话。
#
# `reason` 说清这一拍为什么要重新想（新指令 / 前方出现障碍 / 空转过久），
# 模型靠它区分「用户刚说了话」和「我自己该看一眼了」，否则它会把两种情形
# 当成同一件事，用户没说话时也自己改主意。
#
# `goal` 是自驱时长驻的方向，来自 G 层（`llm/drive.py`）。它不是命令，模型仍要
# 自己把方向翻成 vx/vy/vyaw —— G 只看得见 8 个距离，看不见倾角和台阶高度。
#
# `memory` 是 M 层（`percept/memory.py`）的一句话，`recent` 是 L 层自己最近几轮的
# (秒, 想法, 命令)。两者都是**过去**，不是观测：放在观测之后、命令之前，是为了让
# 模型先看现在、再对照历史，顺序反了它会先入为主。
def _cmd_text(cmd: dict) -> str:
    return " ".join(f"{k}={v:g}" for k, v in cmd.items()
                    if k in ("vx", "vy", "vyaw", "freq", "footswing", "gait"))


# 任务块。进度数字全部来自里程（`percept/memory.py` 的 `travelled`），模型只复述
# 不估算 —— 2026-11-18 实测：任务「往前走两米」，它走了 15.6 米，thought 里还是
# 「任务还差两米没走完」。给它真值之后这句话才有意义。
def _task_block(text: str, task: dict) -> str:
    age = float(task.get("seconds") or 0.0)
    done = bool(task.get("done"))
    stay = task.get("kind") == "stay"
    if stay:
        head = f"当前任务：「{text}」（要一直保持的状态，已经守了 {age:.0f} 秒）"
        lines = [head,
                 "  - 这不是走一段就结束的事：只要人没改口，就得一直守着这一个状态。",
                 "  - 你的 thought 先说这个状态还在不在（还在守着 / 守不住了，因为…）。",
                 "  - 别因为「看起来没别的事可做」就自己找个方向走 —— 那等于把状态丢了。"]
        walked = task.get("walked")
        if walked is not None:
            lines.append(f"  - 守着期间挪了 {float(walked):.1f} 米（系统量的）")
        lines.append("  - 做不到就说清哪一条做不到，别硬撑，也别编。")
        return "\n".join(lines)
    head = f"当前任务：「{text}」（{age:.0f} 秒前你接的）" if not done \
        else f"当前任务：「{text}」（已经做完了，就差你汇报）"
    lines = [head]
    walked = task.get("walked")
    want = task.get("want")
    disp = task.get("disp")
    if walked is not None:
        s = f"  - 进度（系统按里程量的，不用你自己估）：已走 {float(walked):.1f} 米"
        if disp is not None:
            s += f"，离出发点直线 {float(disp):.1f} 米"
        lines.append(s)
    if want:
        left = max(0.0, float(want) - float(walked or 0.0))
        if left > 0.2:
            lines.append(f"  - 要 {float(want):.1f} 米，还差 {left:.1f} 米")
        else:
            lines.append(f"  - 要 {float(want):.1f} 米，已经够了")
    if done:
        lines.append("  - 走够了：这一轮 vx 给 0，用一句话汇报结果，别再往前冲。")
    else:
        lines.append("  - 你的 thought 先说这件事做到哪一步，再说眼前看到什么。")
    lines.append("  - 做不到就说清卡在哪、还差多少；别把任务换成你自己想做的事。")
    return "\n".join(lines)


def build_think(percept_text: str, *, user: str | None = None,
                task: dict | None = None,
                last_command: dict | None = None,
                last_thought: str | None = None,
                reason: str = "", goal: str | None = None,
                aim: str | None = None,
                memory: str | None = None,
                progress: str | None = None,
                has_rays: bool = True,
                recent: list[tuple[float, str, dict]] | None = None,
                dialog: list[tuple[float, str, str]] | None = None) -> list[dict]:
    parts = []
    # 任务放在**最前面**。模型对长上下文的开头和结尾最敏感，中间最不敏感
    # （下面 `recent` 只给三条也是这个原因）。任务排在触发原因之前，是因为
    # 触发原因每拍都换（「前方变近」「视觉打断」），而任务是几十秒不变的那件事
    # —— 2026-11-17 用户说的「我发布任务之后，模型的思考里根本没去思考我的任务」，
    # 根子就是任务只在那一轮的 `user` 里出现过，之后提示词里一个字都没有了。
    if task:
        text = str(task.get("text") or "").strip()
        if text:
            parts.append(_task_block(text, task))
    if reason:
        parts.append(f"触发原因：{reason}")
    if goal:
        parts.append(f"目标：{goal}")
    if aim:
        parts.append(aim)
    parts.append(percept_text)

    if recent:
        # 只给三条。再多就把「现在」挤出注意力，而模型对长上下文的中间部分
        # 最不敏感 —— 它会把第一轮和最后一轮当成全部历史。
        lines = ["最近几轮你自己做的（从旧到新）："]
        for stamp, thought, cmd in recent[-3:]:
            shown = _cmd_text(cmd) or "没下命令"
            # 只有命令的轮次（`EMIT_THOUGHT = False`）不留空洞：一行里两个大空格
            # 看着像解析失败，下一轮会当数据残缺。
            said = thought or "只给命令"
            lines.append(f"  {stamp:5.1f}s  {said}  →  {shown}")
        parts.append("\n".join(lines))

    if memory:
        parts.append(f"记忆：{memory}")

    # 对话：人说过什么、它回过什么。
    #
    # 最后一条如果就是这一轮的 `user`，从历史里去掉 —— 不去掉的话同一句话在
    # 提示词里出现两次（一次在「对话」里、一次在「用户：」那行），模型会当成
    # 人连说了两遍，回话也跟着重复。
    if dialog:
        shown = dialog[:-1] if user and dialog[-1][2] == user else dialog
        if shown:
            lines = ["对话（从旧到新，秒是多久以前；「我」是用户，「它」是你）："]
            for ago, who, text in shown[-6:]:
                lines.append(f"  {ago:5.1f}s  {who}：{text}")
            parts.append("\n".join(lines))

    # 「命令有没有兑现」是模型唯一看不到的那层。它每拍读得到瞬时速度
    # （`机身：… 速度 0.05 m/s`），但读不出「这是我自己命令 0.3 换来的」，
    # 于是会一路重复同一个命令。这一段由执行层事后算好给它。
    if progress:
        parts.append(f"行进情况：{progress}")

    if last_command:
        shown = _cmd_text(last_command)
        parts.append(f"当前命令：{shown or '无'}")
    if last_thought:
        parts.append(f"上一轮你的判断：{last_thought}")
    if user:
        parts.append(f"用户：{user}")
        # 只有这一轮真有人开口才提示回话。每轮都写的话，它会在没人看的时候
        # 自言自语，token 全花在空话上。
        # 这里原来说「是走路指令：reply 写空串」，和上面 `_REPLY_SPEC` 的
        # 「只要这一轮有用户就必须写」直接打架。位置更靠后，模型听它的 ——
        # 2026-11-17 真机上「调头」第一遍回「好，我调头」，第二遍 reply 空，
        # 网页上看着像没收到。三处规则统一成「都要写」。
        parts.append("用户这句是提问或闲聊：用 reply 回他一句，命令别跟着改。"
                     "是走路指令：照它改命令，reply 用一句话说你打算怎么做，"
                     "别留空 —— 人下指令时他要看见反应。")
    parts.append("输出 JSON。")
    return [
        {"role": "system", "content": think_system(has_rays)},
        {"role": "user", "content": "\n".join(parts)},
    ]


# 拼一次对话。`text` 是用户那句话，`state` 是当前命令（可选），给模型一点上下文，
# 让它知道「再快一点」是相对什么。v1 的提示词没有用到 state 的字段，先留着口子。
def build(text: str, state: dict | None = None) -> list[dict]:
    user = text.strip()
    if state:
        now = ", ".join(f"{k}={v:g}" for k, v in state.items() if k in
                        ("vx", "vy", "vyaw", "freq", "footswing"))
        if now:
            user = f"当前命令：{now}\n用户：{user}"
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": user},
    ]
