# （vyaw 的单位是度，不是 rad/s）。提示词从这里拼，不另抄数字。
#
# `schema.py:13` 早就写了这条规矩，这里以前没守：vx 上限在本文件里写过 0.4，
# 而策略训练范围是 ±1.0，改 `COMMAND_RANGE` 的时候这边不会跟着动 —— 结果就是
# 「模型发 0.6，被后端夹回 0.4」，两边都以为自己是对的。这类不一致实测踩过两次
# （vx 和 vyaw，都是自己夹住自己）。
# 整数也带一位小数（1.0 而不是 1）：这几个字段的单位是米每秒、赫兹，`1` 看不出
# 量级，`1.0` 能。
def _num(v: float) -> str:
    v = float(v)
    return f"{v:.1f}" if v.is_integer() else f"{v:g}"


def _rng(key: str) -> str:
    lo, hi = COMMAND_RANGE[key]
    return f"{_num(lo)} 到 {_num(hi)}"


